/* Draft/state assertions use the same pure module as the real settings UI. */
const assert = require("node:assert/strict");
const M = require("../fixtures/wordpress-settings/plugin/model.js");
const state = {revision: 1, settings: {general: {title: "Initial"}, delivery: {enabled: false, email: "saved@example.test"}, advanced: {endpoint: "https://example.test", credentialConfigured: false}}};
const draft = M.draftFrom(state);
assert.equal(M.dirty(draft, state, "general"), false);
const sent = {section: "general", uiValues: {title: "Submitted"}};
const newer = M.copy(draft); newer.general.title = "Newer"; newer.delivery.email = "unsaved@example.test";
const reply = M.copy(state); reply.revision = 2; reply.settings.general.title = "Submitted";
const ack = M.acknowledge(newer, sent, reply);
assert.equal(ack.general.title, "Newer");
assert.equal(ack.delivery.email, "unsaved@example.test");
assert.equal(M.dirty(ack, reply, "general"), true);
assert.equal(state.settings.general.title, "Initial");
assert.equal(newer.general.title, "Newer");
const pending = M.copy(draft); pending.general.title = "Submitted";
const clean = M.acknowledge(pending, sent, reply);
assert.equal(M.dirty(clean, reply, "general"), false);
const resetInput = M.copy(draft); resetInput.delivery.enabled = true;
const reset = M.acknowledge(resetInput, {section: "delivery", uiValues: resetInput.delivery}, state);
assert.equal(reset.delivery.enabled, false);
const secret = M.copy(draft); secret.advanced.credentialAction = "replace"; secret.advanced.credential = "synthetic-only";
const secretReply = M.copy(state); secretReply.settings.advanced.credentialConfigured = true;
const secretAck = M.acknowledge(secret, {section: "advanced", uiValues: secret.advanced}, secretReply);
assert.equal(secretAck.advanced.credential, "");
assert.equal(secretAck.advanced.credentialAction, "keep");
assert.equal(secretAck.advanced.credentialConfigured, true);
const editedSecret = M.copy(secret); editedSecret.advanced.credential = "newer-synthetic-intent";
const retained = M.acknowledge(editedSecret, {section: "advanced", uiValues: secret.advanced}, secretReply);
assert.equal(retained.advanced.credential, "newer-synthetic-intent");
assert.equal(retained.advanced.credentialAction, "replace");
process.stdout.write("Draft reconciliation checks passed: newer edits, unrelated sections, reset and credentials.\n");
